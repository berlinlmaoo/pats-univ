const tokens = fs.readFileSync(`${root}/packages/shared/src/tokens.ts`, 'utf8');
function tokenObject(name) {
  const match = tokens.match(new RegExp(`export const ${name} = (\\{[\\s\\S]*?\\}) as const;`));
  if (!match) throw new Error(`Missing shared token ${name}`);
  return vm.runInNewContext(`(${match[1]})`, {}, { timeout: 1000 });
}
function swiftEnum(name, values) {
  return `enum ${name} {\n` + Object.entries(values).map(([key, value]) => typeof value === 'object'
    ? swiftEnum(key[0].toUpperCase() + key.slice(1), value)
    : `static let ${key}: CGFloat = ${value}\n`).join('') + '}\n';
}
fs.writeFileSync(`${root}/apps/ios/Sources/DesignTokens.swift`, '// Generated by scripts/sync-shared.mjs from packages/shared/src/tokens.ts.\nimport Foundation\n' + swiftEnum('KTMGeometry', tokenObject('ktm')) + swiftEnum('VarsityScale', tokenObject('varsity')) + swiftEnum('CardValueMetrics', Object.fromEntries(Object.entries(tokenObject('fonts').cardValue).filter(([, value]) => typeof value === 'number'))));
